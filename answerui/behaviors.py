@patch
def behaviors(self:Registry):
    "The effective behavior per (selector, event, capture): the last declared in registry order, with the key of the rule that declared it"
    res = {}
    for k,r in self.rules.items():
        for b in r.on: res[(b['sel'], _event(b['ev']), b['cap'])] = dict(b, ev=_event(b['ev']), rule=k)
    return res

@patch
def build_js(self:Registry):
    "The behavior script: one function per distinct handler, one entry per effective behavior"
    bs = self.behaviors().values()
    fns = {js: f'f{i}' for i,js in enumerate(uniqueify([b['js'] for b in bs]))}
    decls = '\n'.join(f'async function {nm}(el, e) {{ {js} }}' for js,nm in fns.items())
    return htmx_js(self.htmx4) + _runtime % (decls, ',\n'.join(_entry(b, fns[b['js']]) for b in bs))
