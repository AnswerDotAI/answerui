@hypelt(sel='button:is([copyfor], [copy])')
def Copy(
    *c,              # Label text; with none, a square button named Copy
    copyfor=None,    # Id of the element whose value or text is copied
    copy=None,       # Fixed text to copy instead of an element's
    variant='quiet', # Button appearance
    **attrs,         # Native button attributes
):
    "Copy fixed text or an element's value or text to the clipboard"
    if not c: attrs.setdefault('aria_label', 'Copy')
    return Btn(CopyIcon(aria_hidden='true') + Check(), *c, copyfor=copyfor, copy=copy, variant=variant, icon=not c, **attrs)

