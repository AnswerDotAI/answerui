@hypelt(sel='[btn]')
def Btn(
    *c,                # Button content
    variant='primary', # primary, secondary, quiet or editable
    size=None,         # sm or lg; None uses the default size
    href=None,         # Link URL; renders an <a> styled as a button
    type='button',     # Explicitly use submit for a form action (ignored with href)
    icon=False,        # Square button holding only an icon; supply an accessible name
    **attrs,           # Native button or anchor attributes
):
    "A raised action, latched by aria-pressed and sunken while busy or expanded"
    kw = dict(btn=True, btn_variant=variant, btn_size=size, btn_icon=icon, **attrs)
    return A(*c, href=href, **kw) if href is not None else _Button(*c, type=type, **kw)

