@hypelt(sel='[field]')
def Field(
    label,      # Label text
    control,    # The control
    hint=None,  # Help text shown under the control
    error=None, # Error message; marks the control invalid
    **attrs,    # Attributes for the field
):
    "A labelled control with optional help and error text"
    if not control.get('id'): control(id=unqid())
    descriptions = []
    if hint: descriptions.append(Small(hint, id=True))
    if error:
        descriptions.append(Small(error, id=True, ui_tone='danger'))
        control(aria_invalid='true')
    if descriptions:
        ids = [control.get('aria-describedby', ''), *(o.id for o in descriptions)]
        control(aria_describedby=' '.join(filter(None, ids)))
    return Div(Label(label, fr=control.id), Div(control, field_control=True), *descriptions,
        field=True, field_inline=control.get('type') in ('checkbox', 'radio'), **attrs)


